def inventory(root=ROOT):
    snapshot = os.environ.get('CAFE_ROUTER_INVENTORY')
    return C.inventory(ROOT, snapshot)


class TestRouterIndex(unittest.TestCase):
    def setUp(self):
        self.temp = tempfile.TemporaryDirectory(prefix='cafe-router-index-')
        self.addCleanup(self.temp.cleanup)
        self.root = Path(self.temp.name) / 'repo'
        shutil.copytree(ROOT, self.root, ignore=shutil.ignore_patterns('.git', 'local', 'target', 'node_modules', '__pycache__'))
        (self.root / 'node_modules').symlink_to(ROOT / 'node_modules', target_is_directory=True)
        self.inventory = inventory(self.root)

    def write_nodes(self, rows):
        (self.root / C.NODES).write_bytes(C.jsonl(rows))

    def kit(self, root=None, check=False):
        root = root or self.root
        cmd = [sys.executable, '-B', 'router/tools/build_index_v2.py', '--nodes', C.NODES, '--out', 'catalogue/router', '--corpus', 'cafe']
        if check: cmd.append('--check')
        result = subprocess.run(cmd, cwd=root, capture_output=True, text=True)
        self.assertEqual(result.returncode, 0, result.stderr)
        if check: self.assertEqual(result.stdout.strip(), 'byte-identical')
        return result

    def test_current_schema_freshness_and_all_coordinates(self):
        nodes, coordinates, identity = R.verify(ROOT, inventory())
        self.assertTrue(identity)
        C.validate_nodes(ROOT, nodes)
        symbols = C.lines(ROOT, C.SYMBOLS)
        self.assertGreater(len(symbols), 0)
        self.assertGreaterEqual(len(nodes), len(C.load(ROOT, C.PROFILE)['files']))
        self.assertEqual(sum(row['symbol'] is not None for row in coordinates), len(symbols))
        self.assertEqual(set(row['path'] for row in coordinates), {row['path'] for row in C.load(ROOT, C.PROFILE)['files']})
        self.assertTrue(all(len('cafe:'.encode()) + len(node['id'].encode()) <= 32 for node in nodes))
        self.assertTrue(all(len(anchor['a'].encode()) <= 64 for node in nodes for anchor in node['anchors']))

    def test_real_three_language_exact_handwritten_locations(self):
        # Handwritten constants from independently reviewed source, not generated by resolver.
        expected = [
            ('cafe_core::capsule_registry::decode_envelope', 'core/src/capsule_registry.rs', 293, 'decode_envelope'),
            ('cafe_shell::preload::cafeBridge::createCafeBridge::getSnapshot', 'src/preload/cafeBridge.js', 201, 'getSnapshot'),
            ('cafe.authority_channel.serve_connector', 'connectors/cafe/authority_channel.py', 27, 'serve_connector'),
            ('cafe_authority_fixture::authority_auth::hmac_sha256', 'core/src/authority_auth.rs', 64, 'hmac_sha256')]
        for key, path, line, name in expected:
            with self.subTest(key=key):
                result = R.resolve(ROOT, key, inventory())
                self.assertEqual({k:result[k] for k in ['path','line','name']}, dict(path=path,line=line,name=name))
                self.assertEqual(result['source_sha256'], C.sha((ROOT / path).read_bytes()))

    def test_deterministic_composition_and_real_kit_check(self):
        first = B.compose(self.root, self.inventory)
        second = B.compose(self.root, self.inventory)
        self.assertEqual(first, second)
        self.assertTrue(all(C.raw(self.root, path) == data for path, data in first.items()))
        before = {str(p.relative_to(self.root / 'catalogue/router')): p.read_bytes() for p in (self.root / 'catalogue/router').rglob('*') if p.is_file()}
        self.kit()
        self.kit(check=True)
        after = {str(p.relative_to(self.root / 'catalogue/router')): p.read_bytes() for p in (self.root / 'catalogue/router').rglob('*') if p.is_file()}
        self.assertEqual(before, after)

    def test_more_than_sixteen_anchors_never_truncated(self):
        nodes = C.lines(ROOT, C.NODES)
        capsule = [n for n in nodes if n['family'] == 'rust-capsule-registry']
        self.assertEqual([len(n['anchors']) for n in capsule], [16, 4])
        self.assertEqual(len({a['a'] for n in capsule for a in n['anchors']}), 20)
        symbols = [s for s in C.lines(ROOT,C.SYMBOLS) if s['path']=='core/src/capsule_registry.rs']
        self.assertEqual(len(symbols),20)
        self.assertEqual({row['symbol'] for row in C.lines(ROOT,C.COORDS) if row['id'] in {n['id'] for n in capsule}}, {s['symbol'] for s in symbols})

    def test_source_changed_without_rebuild_fails(self):
        source = self.root / 'connectors/cafe/authority_channel.py'
        source.write_text('\n' + source.read_text())
        with self.assertRaisesRegex(C.ContractError, 'stale_source_hash'):
            R.resolve(self.root,'cafe.authority_channel.serve_connector',self.inventory)

    def test_duplicate_node_id_fails(self):
        nodes=C.lines(self.root,C.NODES);nodes.append(nodes[0]);self.write_nodes(nodes)
        with self.assertRaisesRegex(C.ContractError,'duplicate_or_foreign_node_id'):
            R.verify(self.root,self.inventory)

    def test_duplicate_anchor_fails(self):
        nodes=C.lines(self.root,C.NODES);node=next(n for n in nodes if len(n['anchors'])<16);node['anchors'].append(dict(node['anchors'][0]));self.write_nodes(nodes)
        with self.assertRaisesRegex(C.ContractError,'duplicate_family_anchor'):
            R.verify(self.root,self.inventory)
        source=self.root/'subjects/backend/page.md';source.write_text(source.read_text()+'\n<a id="backend-overview"></a>\n')
        with self.assertRaisesRegex(C.ContractError,'duplicate_source_anchor'):
            B.compose(self.root,self.inventory)

    def test_escaping_path_fails(self):
        text=(self.root/C.ROUTES).read_text();lines=text.splitlines();ident=lines[1].split('\t')[0];lines[1]=ident+'\t../outside';(self.root/C.ROUTES).write_text('\n'.join(lines)+'\n')
        with self.assertRaisesRegex(C.ContractError,'unsafe_relative_path'):
            R.verify(self.root,self.inventory)

    def test_overlong_id_and_multibyte_anchor_fail_without_clipping(self):
        nodes=C.lines(self.root,C.NODES);nodes[0]['id']='n'*28;self.write_nodes(nodes)
        with self.assertRaisesRegex(C.ContractError,'node_identity_width_or_shape'):
            R.verify(self.root,self.inventory)
        nodes=C.lines(ROOT,C.NODES);nodes[0]['anchors'][0]['a']='a'*32+'é'*17
        with self.assertRaisesRegex(C.ContractError,'anchor_identity_width_or_shape'):
            C.validate_nodes(self.root,nodes)

    def test_removed_export_after_honest_rebuild_still_fails_admitted_symbols(self):
        source=self.root/'connectors/cafe/authority_channel.py';text=source.read_text();self.assertEqual(text.count('async def serve_connector('),1);source.write_text(text.replace('async def serve_connector(','async def _serve_connector(',1))
        old_symbols=C.raw(self.root,C.SYMBOLS)
        fresh=B.compose(self.root,self.inventory)
        with self.assertRaisesRegex(C.ContractError,'public_symbol_removed_requires_review'):
            B.enforce_admitted_symbols(self.root,fresh)
        # Genuine fresh composition and vendor index rebuild, retaining admitted contract.
        B.write_products(self.root,{p:data for p,data in fresh.items() if p!=C.SYMBOLS})
        self.assertEqual(C.raw(self.root,C.SYMBOLS),old_symbols)
        self.kit();self.kit(check=True)
        self.assertEqual(C.check_index(self.root),C.raw(self.root,'catalogue/router/ID').decode().strip())
        with self.assertRaisesRegex(C.ContractError,'admitted_symbol_coverage_mismatch'):
            R.resolve(self.root,'cafe.authority_channel.serve_connector',self.inventory)

    def test_missing_params_cannot_be_presented_calibrated(self):
        (self.root/C.CALIBRATION).write_bytes(C.canonical({'schema':'cafe.calibration.v1','corpus':'cafe','status':'calibrated','params':'catalogue/router/params.json'}))
        self.assertFalse((self.root/'catalogue/router/params.json').exists())
        with self.assertRaisesRegex(C.ContractError,'calibrated_claim_without_params'):
            R.verify(self.root,self.inventory)

    def test_exact_keys_ambiguity_and_uncalibrated_ack(self):
        with self.assertRaisesRegex(C.ContractError,'missing_or_ambiguous_exact_key'):
            R.resolve(ROOT,'file',inventory())
        exact=R.resolve(ROOT,'cafe:backend-book#backend-overview',inventory());self.assertEqual(exact['path'],'subjects/backend/page.md');self.assertEqual(exact['name'],'backend-overview')
        with self.assertRaises(C.ContractError):R.resolve(ROOT,'cafe:rust-capsule-registry'+'x'*32,inventory())
        with self.assertRaisesRegex(C.ContractError,'explicit_uncalibrated_ack_required'):R.route(ROOT,'capsule registry',inventory())
        result=R.route(ROOT,'capsule registry',inventory(),True);self.assertEqual(result['calibration'],'uncalibrated')
        # A bare ID/anchor collision is ambiguous; explicit corpus/id disambiguates.
        source=self.root/'subjects/backend/page.md';source.write_text(source.read_text()+'\n<a id="rust-main"></a>\n')
        B.write_products(self.root,B.compose(self.root,self.inventory));self.kit()
        with self.assertRaisesRegex(C.ContractError,'missing_or_ambiguous_exact_key'):R.resolve(self.root,'rust-main',self.inventory)
        self.assertEqual(R.resolve(self.root,'cafe:rust-main',self.inventory)['path'],'core/src/main.rs')
        self.assertEqual(R.resolve(self.root,'backend-book#rust-main',self.inventory)['path'],'subjects/backend/page.md')

    def test_schema_unknown_field_and_unlisted_source_fail(self):
        nodes=C.lines(self.root,C.NODES);nodes[0]['unknown']=True
        with self.assertRaisesRegex(C.ContractError,'node_schema_invalid'):C.validate_nodes(self.root,nodes)
        new='connectors/cafe/new_api.py';(self.root/new).write_text('def new_api(): pass\n')
        with self.assertRaisesRegex(C.ContractError,'source_profile_coverage_incomplete'):B.compose(self.root,self.inventory+[new])

    def test_rust_optional_root_default_refuses_path_override(self):
        rust=C.tool(self.root,'tools/extract_rust.py');profile=C.load(self.root,C.PROFILE)['rust_roots'][1]
        with self.assertRaises(rust.ExtractionError):rust.extract(self.root,profile['files'],self.inventory,profile['cfg'])
        wrong=dict(profile['module_paths']);wrong['core/tests/authority_fixture.rs::authority_auth']='core/src/main.rs'
        with self.assertRaises(rust.ExtractionError):rust.extract(self.root,profile['files'],self.inventory,profile['cfg'],entry=profile['entry'],crate=profile['crate'],module_paths=wrong)

    def test_clipped_namespace_and_stale_coordinate_line_fail(self):
        original=C.raw(self.root,C.PROFILE);profile=C.decode(original)
        row=next(r for r in profile['files'] if r['path']=='connectors/cafe/authority_channel.py')
        row['symbol_prefix']='cafe.authority_channel.serve_'
        (self.root/C.PROFILE).write_bytes(C.canonical(profile))
        with self.assertRaisesRegex(C.ContractError,'clipped_or_incorrect_module_namespace'):B.compose(self.root,self.inventory)
        (self.root/C.PROFILE).write_bytes(original)
        coordinates=C.lines(self.root,C.COORDS);row=next(r for r in coordinates if r['symbol']=='cafe.authority_channel.serve_connector');row['line']=1
        (self.root/C.COORDS).write_bytes(C.jsonl(coordinates))
        with self.assertRaisesRegex(C.ContractError,'stale_coordinate_line_or_name'):R.verify(self.root,self.inventory)

    def test_qualification_structural_pass_is_never_qualified(self):
        q=C.tool(ROOT,'tools/qualify_cafe_router.py');legs=tuple(q.Leg(name,True,(q.Check(name,True,0,1),)) for name in q.LEG_NAMES);report=q.summarize(legs,'fixture');q.validate_report(report,legs)
        self.assertEqual(report['verdict'],'router available (uncalibrated)');self.assertEqual(report['state'],'available_uncalibrated');self.assertFalse(report['calibrated']);self.assertEqual(report['legs']['resolver_index']['availability'],'available_uncalibrated');self.assertEqual(q.exit_code(legs),0);self.assertNotEqual(q.exit_code(legs,True),0)
        report['verdict']='qualified'
        with self.assertRaises(ValueError):q.validate_report(report,legs)


