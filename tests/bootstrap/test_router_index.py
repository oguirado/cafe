class TestRouterIndex(unittest.TestCase):
    def setUp(self):
        self.temp = tempfile.TemporaryDirectory(prefix='cafe-router-index-')
        self.addCleanup(self.temp.cleanup)
        self.root = Path(self.temp.name) / 'repo'
        shutil.copytree(ROOT, self.root, ignore=shutil.ignore_patterns('.git', 'local', 'target', 'node_modules', '__pycache__'))
        (self.root / 'node_modules').symlink_to(ROOT / 'node_modules', target_is_directory=True)
        self.inventory = inventory(self.root)

    def write_nodes(self, rows):
        (self.root / C.NODES).write_bytes(C.jsonl(rows))

    def kit(self, root=None, check=False):
        root = root or self.root
        cmd = [sys.executable, '-B', 'router/tools/build_index_v2.py', '--nodes', C.NODES, '--out', 'catalogue/router', '--corpus', 'cafe']
        if check: cmd.append('--check')
        result = subprocess.run(cmd, cwd=root, capture_output=True, text=True)
        self.assertEqual(result.returncode, 0, result.stderr)
        if check: self.assertEqual(result.stdout.strip(), 'byte-identical')
        return result

    def test_current_schema_freshness_and_all_coordinates(self):
        nodes, coordinates, identity = R.verify(ROOT, inventory())
        self.assertTrue(identity)
        C.validate_nodes(ROOT, nodes)
        symbols = C.lines(ROOT, C.SYMBOLS)
        self.assertGreater(len(symbols), 0)
        self.assertGreaterEqual(len(nodes), len(C.load(ROOT, C.PROFILE)['files']))
        self.assertEqual(sum(row['symbol'] is not None for row in coordinates), len(symbols))
        self.assertEqual(set(row['path'] for row in coordinates), {row['path'] for row in C.load(ROOT, C.PROFILE)['files']})
        self.assertTrue(all(len('cafe:'.encode()) + len(node['id'].encode()) <= 32 for node in nodes))
        self.assertTrue(all(len(anchor['a'].encode()) <= 64 for node in nodes for anchor in node['anchors']))

    def test_real_three_language_exact_handwritten_locations(self):
        # Handwritten constants from independently reviewed source, not generated by resolver.
        expected = [
            ('cafe_core::capsule_registry::decode_envelope', 'core/src/capsule_registry.rs', 293, 'decode_envelope'),
            ('cafe_shell::preload::cafeBridge::createCafeBridge::getSnapshot', 'src/preload/cafeBridge.js', 201, 'getSnapshot'),
            ('cafe.authority_channel.serve_connector', 'connectors/cafe/authority_channel.py', 27, 'serve_connector'),
            ('cafe_authority_fixture::authority_auth::hmac_sha256', 'core/src/authority_auth.rs', 111, 'hmac_sha256')]
        for key, path, line, name in expected:
            with self.subTest(key=key):
                result = R.resolve(ROOT, key, inventory())
                self.assertEqual({k:result[k] for k in ['path','line','name']}, dict(path=path,line=line,name=name))
                self.assertEqual(result['source_sha256'], C.sha((ROOT / path).read_bytes()))

    def test_deterministic_composition_and_real_kit_check(self):
        first = B.compose(self.root, self.inventory)
        second = B.compose(self.root, self.inventory)
        self.assertEqual(first, second)
        self.assertTrue(all(C.raw(self.root, path) == data for path, data in first.items()))
        before = {str(p.relative_to(self.root / 'catalogue/router')): p.read_bytes() for p in (self.root / 'catalogue/router').rglob('*') if p.is_file()}
        self.kit()
        self.kit(check=True)
        after = {str(p.relative_to(self.root / 'catalogue/router')): p.read_bytes() for p in (self.root / 'catalogue/router').rglob('*') if p.is_file()}
        self.assertEqual(before, after)

